"""Generate sObject Tree import files for the Meridian demo dataset.

Run this, then import with the plan it writes:

    python salesforce/demo-data/seed.py
    sf data import tree --plan salesforce/demo-data/plan.json --target-org dealrescue

Two things this has to work around, both from docs/salesforce-app.md section 6:

1. **Stage names differ from the fixtures.** The org uses the standard picklist
   (Prospecting / Qualification / Proposal Price Quote / Negotiation Review); the
   fixtures use a shorter vocabulary. STAGE_MAP is the single place that
   translation lives.

2. **OpportunityHistory cannot be seeded.** Stage history rows are generated by
   Salesforce when a stage actually changes, always stamped now. The opportunity
   is created at its *starting* stage here; `advance.py` then walks it through
   the real stage changes so history rows exist at all. Their dates will be
   today's -- that limitation is inherent, not a bug in this script.

Every record is tagged "Deal Rescue demo" in Description so the demo data can be
told apart from the 44 opportunities already in this org, and cleaned up safely.
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
TAG = "Deal Rescue demo"

# fixture vocabulary -> this org's standard picklist
STAGE_MAP = {
    "Discovery": "Prospecting",
    "Qualification": "Qualification",
    "Proposal": "Proposal/Price Quote",
    "Negotiation": "Negotiation/Review",
}

ACCOUNTS = [
    ("acctMeridian", "Meridian Fabrication", "Fort Wayne", "IN", 180_000_000),
    ("acctCalumet", "Calumet Coatings", "Hammond", "IN", 40_000_000),
    ("acctWabash", "Wabash Tool & Die", "Wabash", "IN", 25_000_000),
    ("acctNorthgate", "Northgate Stamping", "Kokomo", "IN", 95_000_000),
    ("acctDelaware", "Delaware Valley Machining", "Muncie", "IN", 60_000_000),
    ("acctKokomo", "Kokomo Fabricators", "Kokomo", "IN", 18_000_000),
]

CONTACTS = [
    ("conDana", "Dana", "Kowalski", "VP Operations", "dana.kowalski@meridianfab.example"),
    ("conRay", "Ray", "Gutierrez", "Plant Manager", "ray.gutierrez@meridianfab.example"),
    ("conAnne", "Anne", "Park", "CFO", "anne.park@meridianfab.example"),
]

# ref, account ref, name, amount, START stage (fixture vocab), close date
OPPORTUNITIES = [
    ("oppMeridian", "acctMeridian", "Plant 2 Quoting System Replacement",
     240_000, "Discovery", "2026-09-30"),
    ("oppCalumet", "acctCalumet", "Coating Line Scheduling Upgrade",
     95_000, "Qualification", "2026-10-15"),
    ("oppWabash", "acctWabash", "Shop Floor Tablet Rollout",
     48_000, "Proposal", "2026-09-30"),
    ("oppNorthgate", "acctNorthgate", "ERP Quoting Integration Phase 2",
     310_000, "Negotiation", "2026-11-20"),
    ("oppDelaware", "acctDelaware", "Maintenance Work Order Portal",
     72_000, "Discovery", "2026-12-01"),
    ("oppKokomo", "acctKokomo", "Weld Cell Utilization Dashboard",
     26_000, "Qualification", "2026-10-31"),
]

CONTACT_ROLES = [
    ("ocrDana", "oppMeridian", "conDana", "Decision Maker", True),
    ("ocrRay", "oppMeridian", "conRay", "Technical Buyer", False),
    ("ocrAnne", "oppMeridian", "conAnne", "Economic Buyer", False),
]

# Meetings become Events so the live adapter can tell them from emails/calls.
EVENTS = [
    ("evtDiscovery", "oppMeridian", "conDana", "2026-03-04",
     "Discovery call - Dana + Ray"),
    ("evtNegotiation", "oppMeridian", "conDana", "2026-06-10",
     "Negotiation kickoff - terms review"),
    ("evtReview", "oppMeridian", "conRay", "2026-07-14",
     "Solution review with Dana + Ray (recorded)"),
]

# Everything else is a Task. The last three are the ghosted follow-ups.
TASKS = [
    ("tskProposal", "oppMeridian", "conDana", "2026-04-18",
     "Proposal sent - $240K quoting system"),
    ("tskFollowup", "oppMeridian", "conDana", "2026-05-12",
     "Follow-up call with Dana"),
    ("tskPing1", "oppMeridian", "conRay", "2026-08-12",
     "Checking in on next steps"),
    ("tskPing2", "oppMeridian", "conRay", "2026-08-21",
     "Following up on the quoting rollout"),
    ("tskPing3", "oppMeridian", "conRay", "2026-09-01",
     "Should I close this out?"),
    # One task per filler deal, dated to drive its stall_days.
    ("tskCalumet", "oppCalumet", None, "2026-08-14", "Follow-up"),
    ("tskWabash", "oppWabash", None, "2026-07-29", "Follow-up"),
    ("tskNorthgate", "oppNorthgate", None, "2026-09-05", "Follow-up"),
    ("tskDelaware", "oppDelaware", None, "2026-08-25", "Follow-up"),
    ("tskKokomo", "oppKokomo", None, "2026-09-12", "Follow-up"),
]


def record(sobject: str, ref: str, **fields) -> dict:
    return {"attributes": {"type": sobject, "referenceId": ref}, **fields}


def write(name: str, records: list[dict]) -> str:
    path = HERE / name
    path.write_text(json.dumps({"records": records}, indent=2), encoding="utf-8")
    print(f"  {name:28s} {len(records)} records")
    return name


def main() -> None:
    print("writing tree import files:")

    accounts = [
        record(
            "Account", ref,
            Name=name, Industry="Manufacturing", AnnualRevenue=revenue,
            BillingCity=city, BillingState=state, Description=TAG,
        )
        for ref, name, city, state, revenue in ACCOUNTS
    ]

    contacts = [
        record(
            "Contact", ref,
            FirstName=first, LastName=last, Title=title, Email=email,
            AccountId="@acctMeridian", Description=TAG,
        )
        for ref, first, last, title, email in CONTACTS
    ]

    opportunities = [
        record(
            "Opportunity", ref,
            Name=name, AccountId=f"@{acct}", Amount=amount,
            StageName=STAGE_MAP[stage], CloseDate=close, Description=TAG,
        )
        for ref, acct, name, amount, stage, close in OPPORTUNITIES
    ]

    roles = [
        record(
            "OpportunityContactRole", ref,
            OpportunityId=f"@{opp}", ContactId=f"@{con}",
            Role=role, IsPrimary=primary,
        )
        for ref, opp, con, role, primary in CONTACT_ROLES
    ]

    events = [
        record(
            "Event", ref,
            Subject=subject, WhatId=f"@{opp}", WhoId=f"@{con}",
            StartDateTime=f"{day}T15:00:00.000+0000",
            EndDateTime=f"{day}T16:00:00.000+0000",
            Description=TAG,
        )
        for ref, opp, con, day, subject in EVENTS
    ]

    tasks = []
    for ref, opp, con, day, subject in TASKS:
        fields = dict(
            Subject=subject, WhatId=f"@{opp}", ActivityDate=day,
            Status="Completed", Description=TAG,
        )
        if con:
            fields["WhoId"] = f"@{con}"
        tasks.append(record("Task", ref, **fields))

    plan = [
        {"sobject": "Account", "saveRefs": True, "resolveRefs": False,
         "files": [write("accounts.json", accounts)]},
        {"sobject": "Contact", "saveRefs": True, "resolveRefs": True,
         "files": [write("contacts.json", contacts)]},
        {"sobject": "Opportunity", "saveRefs": True, "resolveRefs": True,
         "files": [write("opportunities.json", opportunities)]},
        {"sobject": "OpportunityContactRole", "saveRefs": False, "resolveRefs": True,
         "files": [write("contact-roles.json", roles)]},
        {"sobject": "Event", "saveRefs": False, "resolveRefs": True,
         "files": [write("events.json", events)]},
        {"sobject": "Task", "saveRefs": False, "resolveRefs": True,
         "files": [write("tasks.json", tasks)]},
    ]

    (HERE / "plan.json").write_text(json.dumps(plan, indent=2), encoding="utf-8")
    print("\nplan.json written. Import with:")
    print("  sf data import tree --plan salesforce/demo-data/plan.json --target-org dealrescue")


if __name__ == "__main__":
    main()
